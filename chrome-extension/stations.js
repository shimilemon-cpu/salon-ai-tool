/**
 * 登録駅から同路線の近隣駅を最大 count 件取得する。
 * radius: 登録駅の前後何駅まで含めるか（デフォルト5）
 */
function getNearbyStations(homeStation, radius = 5, count = 10) {
  const nearby = new Map(); // station → min distance
  for (const [, stations] of Object.entries(LINES)) {
    const idx = stations.indexOf(homeStation);
    if (idx === -1) continue;
    for (let d = 1; d <= radius; d++) {
      for (const offset of [-d, d]) {
        const s = stations[idx + offset];
        if (s && s !== homeStation) {
          const prev = nearby.get(s);
          if (prev === undefined || d < prev) nearby.set(s, d);
        }
      }
    }
  }
  return [...nearby.entries()]
    .sort((a, b) => a[1] - b[1])
    .slice(0, count)
    .map(([s]) => s);
}

/**
 * 駅名の前方一致検索（候補サジェスト用）
 */
function searchStations(query) {
  if (!query) return [];
  const q = query.trim();
  const seen = new Set();
  const results = [];
  for (const stations of Object.values(LINES)) {
    for (const s of stations) {
      if (s.startsWith(q) && !seen.has(s)) {
        seen.add(s);
        results.push(s);
      }
    }
  }
  return results.slice(0, 8);
}
